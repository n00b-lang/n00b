#!/usr/bin/env python3
"""
WP-005 — embed the audit-rule-file metagrammar as a C string
constant in a generated header. Reads the input BNF file and
writes a header defining N00B_AUDIT_RULE_FILE_METAGRAMMAR as a
static const char array carrying the file contents with normalized
LF newlines.

Usage: embed_metagrammar.py <input.bnf> <output.h>
"""
import sys


def c_escape(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "\"":
            out.append("\\\"")
        elif ch == "\t":
            out.append("\\t")
        elif 0x20 <= ord(ch) <= 0x7e:
            out.append(ch)
        else:
            out.extend(f"\\{b:03o}" for b in ch.encode("utf-8"))
    return "".join(out)


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: embed_metagrammar.py <input.bnf> <output.h>",
              file=sys.stderr)
        return 1
    in_path, out_path = sys.argv[1], sys.argv[2]
    with open(in_path, "r", encoding="utf-8", newline=None) as fh:
        src = fh.read()
    lines = src.split("\n")
    n = len(lines)
    out_lines = [
        "#pragma once",
        "",
        "/* Auto-generated by scripts/embed_metagrammar.py from",
        " * grammars/audit-rule-file.bnf - do not edit. */",
        "",
        "static const char N00B_AUDIT_RULE_FILE_METAGRAMMAR[] =",
    ]
    for i, line in enumerate(lines):
        esc = c_escape(line)
        suffix = "\\n" if i + 1 < n else ""
        out_lines.append("    \"" + esc + suffix + "\"")
    out_lines.append("    \"\";")
    out_lines.append("")
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out_lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
